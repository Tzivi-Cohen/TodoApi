using System.IdentityModel.Tokens.Jwt;
using System.Security.Claims;
using System.Text;
using Microsoft.AspNetCore.Authentication.JwtBearer;
using Microsoft.AspNetCore.Identity;
using Microsoft.EntityFrameworkCore;
using Microsoft.IdentityModel.Tokens;
using Microsoft.OpenApi.Models;
using TodoApi.Data;
using TodoApi.Models;

var builder = WebApplication.CreateBuilder(args);

// Connection string is read from configuration (User Secrets in development).
var connectionString = builder.Configuration.GetConnectionString("ToDoDB")
    ?? throw new InvalidOperationException("Connection string 'ToDoDB' was not found.");

builder.Services.AddDbContext<ToDoDbContext>(options =>
    options.UseMySql(connectionString, ServerVersion.Parse("8.0.46-mysql")));

// CORS - allow only the local React client
builder.Services.AddCors(options =>
{
    options.AddPolicy("ReactClient", policy =>
        policy.WithOrigins("http://localhost:3000")
              .AllowAnyMethod()
              .AllowAnyHeader());
});

// JWT - the signing key is read from configuration (User Secrets in development)
var jwtKey = builder.Configuration["Jwt:Key"]
    ?? throw new InvalidOperationException("Configuration value 'Jwt:Key' was not found.");
var jwtIssuer = builder.Configuration["Jwt:Issuer"];
var jwtAudience = builder.Configuration["Jwt:Audience"];
var signingKey = new SymmetricSecurityKey(Encoding.UTF8.GetBytes(jwtKey));

builder.Services.AddAuthentication(JwtBearerDefaults.AuthenticationScheme)
    .AddJwtBearer(options =>
    {
        options.TokenValidationParameters = new TokenValidationParameters
        {
            ValidateIssuer = true,
            ValidateAudience = true,
            ValidateLifetime = true,
            ValidateIssuerSigningKey = true,
            ValidIssuer = jwtIssuer,
            ValidAudience = jwtAudience,
            IssuerSigningKey = signingKey
        };
    });
builder.Services.AddAuthorization();

// Swagger (with a JWT "Authorize" button)
builder.Services.AddEndpointsApiExplorer();
builder.Services.AddSwaggerGen(options =>
{
    var bearer = new OpenApiSecurityScheme
    {
        Type = SecuritySchemeType.Http,
        Scheme = "bearer",
        BearerFormat = "JWT",
        Description = "Paste the token returned by /login",
        Reference = new OpenApiReference { Type = ReferenceType.SecurityScheme, Id = "Bearer" }
    };
    options.AddSecurityDefinition("Bearer", bearer);
    options.AddSecurityRequirement(new OpenApiSecurityRequirement { [bearer] = Array.Empty<string>() });
});

var app = builder.Build();

app.UseCors("ReactClient");
app.UseAuthentication();
app.UseAuthorization();

if (app.Environment.IsDevelopment())
{
    app.UseSwagger();
    app.UseSwaggerUI();
}

app.MapGet("/", () => "Hello World!");

var hasher = new PasswordHasher<User>();

// Register a new user
app.MapPost("/register", async (LoginRequest input, ToDoDbContext db) =>
{
    var username = input.Username?.Trim();
    if (string.IsNullOrEmpty(username) || username.Length < 3 || username.Length > 100)
        return Results.BadRequest("Username must be 3-100 characters.");
    if (string.IsNullOrEmpty(input.Password) || input.Password.Length < 6 || input.Password.Length > 100)
        return Results.BadRequest("Password must be 6-100 characters.");
    if (await db.Users.AnyAsync(u => u.Username == username))
        return Results.Conflict("Username already exists.");

    var user = new User { Username = username };
    user.PasswordHash = hasher.HashPassword(user, input.Password);

    db.Users.Add(user);
    await db.SaveChangesAsync();
    return Results.Ok(new { token = CreateToken(user) });
});

// Log in an existing user
app.MapPost("/login", async (LoginRequest input, ToDoDbContext db) =>
{
    if (string.IsNullOrWhiteSpace(input.Username) || string.IsNullOrEmpty(input.Password))
        return Results.BadRequest("Username and password are required.");

    var user = await db.Users.FirstOrDefaultAsync(u => u.Username == input.Username.Trim());
    if (user is null ||
        hasher.VerifyHashedPassword(user, user.PasswordHash, input.Password) == PasswordVerificationResult.Failed)
        return Results.Unauthorized();

    return Results.Ok(new { token = CreateToken(user) });
});

// Get all items
app.MapGet("/items", async (ToDoDbContext db) =>
    await db.Items.ToListAsync()).RequireAuthorization();

// Create a new item
app.MapPost("/items", async (Item item, ToDoDbContext db) =>
{
    if (string.IsNullOrWhiteSpace(item.Name))
        return Results.BadRequest("Name is required.");
    if (item.Name.Length > 100)
        return Results.BadRequest("Name must be at most 100 characters.");

    item.Id = 0; // Id is generated by the database
    item.IsComplete ??= false;

    db.Items.Add(item);
    await db.SaveChangesAsync();
    return Results.Created($"/items/{item.Id}", item);
}).RequireAuthorization();

// Update an existing item
app.MapPut("/items/{id}", async (int id, Item input, ToDoDbContext db) =>
{
    var item = await db.Items.FindAsync(id);
    if (item is null)
        return Results.NotFound($"Item {id} was not found.");

    if (input.Name is not null)
    {
        if (string.IsNullOrWhiteSpace(input.Name))
            return Results.BadRequest("Name cannot be empty.");
        if (input.Name.Length > 100)
            return Results.BadRequest("Name must be at most 100 characters.");
        item.Name = input.Name;
    }

    if (input.IsComplete is not null)
        item.IsComplete = input.IsComplete;

    await db.SaveChangesAsync();
    return Results.Ok(item);
}).RequireAuthorization();

// Delete an item
app.MapDelete("/items/{id}", async (int id, ToDoDbContext db) =>
{
    var item = await db.Items.FindAsync(id);
    if (item is null)
        return Results.NotFound($"Item {id} was not found.");

    db.Items.Remove(item);
    await db.SaveChangesAsync();
    return Results.NoContent();
}).RequireAuthorization();

app.Run();

// Creates a signed JWT (valid for 2 hours) for the given user
string CreateToken(User user)
{
    var claims = new[]
    {
        new Claim(ClaimTypes.NameIdentifier, user.Id.ToString()),
        new Claim(ClaimTypes.Name, user.Username)
    };

    var token = new JwtSecurityToken(
        issuer: jwtIssuer,
        audience: jwtAudience,
        claims: claims,
        expires: DateTime.UtcNow.AddHours(2),
        signingCredentials: new SigningCredentials(signingKey, SecurityAlgorithms.HmacSha256));

    return new JwtSecurityTokenHandler().WriteToken(token);
}

record LoginRequest(string Username, string Password);
